import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const files=['site.css','header.css','commercial-hub.css','home.css'];
const css='/* Generated by scripts/build-homepage-css.mjs; preserve source stylesheet order. */\n'+files.map(file=>'/* '+file+' */\n'+fs.readFileSync(path.join(root,'assets/css',file),'utf8')).join('\n');
fs.writeFileSync(path.join(root,'assets/css/homepage-bundle.css'),css);
for(const file of ['index.html','es/index.html']){
 const p=path.join(root,file);let html=fs.readFileSync(p,'utf8');
 if(html.includes('<!-- MT homepage CSS start -->'))html=html.replace(/<!-- MT homepage CSS start -->[\s\S]*?<!-- MT homepage CSS end -->/, '<!-- MT homepage CSS start -->\n  <link rel="stylesheet" href="/assets/css/homepage-bundle.css?v=20261009-1">\n  <!-- MT homepage CSS end -->');
 else{let first=true;html=html.replace(/<link rel="stylesheet" href="\/assets\/css\/(?:site|header|commercial-hub|home)\.css[^\"]*">/g,()=>{if(!first)return '';first=false;return '<!-- MT homepage CSS start -->\n  <link rel="stylesheet" href="/assets/css/homepage-bundle.css?v=20261009-1">\n  <!-- MT homepage CSS end -->'});}
 fs.writeFileSync(p,html.split("\n").map(line=>line.trimEnd()).join("\n"));
}
console.log('Combined homepage CSS',Buffer.byteLength(css),'bytes');
